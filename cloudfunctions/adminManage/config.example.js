/**
 * adminManage 云函数配置模板（复制本文件为 config.js 后填真实值）
 * ============================================================
 * 用法：
 *   1. 复制本文件为同目录下的 config.js
 *   2. 打开 config.js，把下面的示例值替换成真实值
 *   3. 随函数一起部署到云端
 * 说明：代码优先读控制台环境变量 process.env；若平台没有环境变量入口（如 EMAS
 *       小程序云），就用 config.js 兜底。config.js 已被 .gitignore 忽略，不会提交。
 *
 * ⚠️ 只有 ADMIN_PASSWORD 是必填的。它绝不进小程序包 —— 这正是本模块存在的理由：
 *    miniprogram/config.js 里的 clientSecret 会随包发到用户手机上，所以任何放在
 *    小程序前端的密码校验都形同虚设（攻击者拿到 clientSecret 直接调数据库写
 *    BITZHAdministrator 即可，根本不会执行到我们的密码输入框）。
 */
module.exports = {
  // ---- 必填：管理员操作密码（明文）----
  // 建议 16 位以上、与其他系统不重用的随机串。设了它，下面的 SHA256 就不用管。
  ADMIN_PASSWORD: '在这里填一个足够长的随机密码',

  // ---- 可选：改用摘要代替明文 ----
  // 想让明文只存在于密码管理器里时，把 ADMIN_PASSWORD 留空、在这里填它的 sha256（64 位小写 hex）。
  // 生成：node -e "console.log(require('crypto').createHash('sha256').update('你的密码').digest('hex'))"
  // 【注意】sha256 不抗暴力破解，它换来的是"配置文件里没明文"，不是"密码更安全"。
  //         两者都填时优先用本项。
  ADMIN_PASSWORD_SHA256: '',

  // ---- 可选：身份来源开关 ----
  // 实测出服务端能独立确认调用者身份（action:'whoami' 返回 trustedIdMatchesClaim:true）之后，
  // 强烈建议设成 '1' —— 那会彻底关掉"调用者身份由客户端自报、可伪造"的降级分支。
  // '1' = 只认服务端身份，取不到就拒绝（硬失败，不降级）
  // '0' = 强制按"不可信"处理（id 仍取最好来源，但 list 也要密码）。用于验证单锁路径。
  // ''  = 默认：能取到可信身份就用，取不到就退回客户端自报（不推荐长期这样跑）
  ADMIN_TRUST_CALLER_ID: '',

  // ---- 可选：一次性诊断开关 ----
  // 设 '1' 后 action:'whoami' 会回显具体 userId 供比对；测完务必改回 '0' 重新发布。
  ADMIN_DIAG: '',

  // ---- 可选：阈值（不填用括号里的默认值）----
  MAX_ADMINS: '',    // 管理员数量上限（20）
  PW_MAX_FAILS: '',  // 连续错几次密码就锁定（5）
  PW_LOCK_MS: '',    // 锁定时长，毫秒（600000 = 10 分钟）
};
